public class myMath {

  /*
   * PRE: None
   * Description: Method takes 2 numbers
   * and multiples them together
   * POST: The product of the 2 numbers is returned
  */
  public int multiple(int a, int b) {

    int product = 0;
    product = a * b;

    return product;
    
  }

    /*
   * PRE: None
   * Description: Method takes 2 numbers
   * and adds them together
   * POST: The sum of the 2 numbers is returned
  */
  public int addition(int a, int b) {

    int sum = 0;
    sum = a + b;
    
    return sum;
    
  }
  
}